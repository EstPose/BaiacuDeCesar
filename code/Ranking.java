    public Ranking() {
        initComponents();
        setModal(true);
        
        if (!info.dados.isEmpty()) {
            ArrayList<jogador> order = new ArrayList<>(info.dados);
            order.sort((a, b) -> Integer.compare(b.nivel, a.nivel));

            ArrayList<String> lista = new ArrayList<>();
            

            for (int a = 0; a < order.size(); a++) {
                int nivel = order.get(a).nivel;
                int nivel_ajustado = ((nivel - 1) % 4) + 1;
                String item = (a+1) + ". ";
                
                if (nivel == 0) {
                    item += "Tutorial ....... ";
                } else if (nivel < 5) {
                    item += "Fehu ";
                    item += nivel_ajustado + " ......... ";
                } else if (nivel < 9) {
                    item += "Uruz ";
                    item += nivel_ajustado + " ......... ";
                } else if (nivel < 13) {
                    item += "Thurisaz ";
                    item += nivel_ajustado + " ..... ";
                } else if (nivel < 17) {
                    item += "Ansuz ";
                    item += nivel_ajustado + " ........ ";
                } else {
                    item += "Finalizado ..... ";
                }
                
                item += order.get(a).nome;
                
                lista.add(item);
            }
            
            DefaultListModel<String> model = new DefaultListModel<>();
            model.addAll(lista);
            lstRanking.setModel(model);
        }
    }

